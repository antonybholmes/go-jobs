    (1, uuidv7(), 'submitted', 'Job has been submitted'),
    (2, uuidv7(), 'pending', 'Job is pending'),
    (3, uuidv7(), 'running', 'Job is running'),
    (4, uuidv7(), 'completed', 'Job is completed'),
    (5, uuidv7(), 'failed', 'Job has failed');


CREATE TABLE IF NOT EXISTS jobs (
    id uuid PRIMARY KEY DEFAULT uuidv7(),
    type_id INTEGER NOT NULL REFERENCES job_types(id) DEFAULT 1,
    status_id INTEGER NOT NULL REFERENCES job_statuses(id) DEFAULT 1,
    user_id uuid NOT NULL,
    email TEXT NOT NULL,
    name TEXT,
    description TEXT,
    -- The type of job (e.g., "email", "crispr")
   
    -- The timestamp when the job was created
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS jobs_type_id_idx
    ON jobs (type_id);

CREATE INDEX IF NOT EXISTS jobs_status_id_idx
    ON jobs (status_id);

