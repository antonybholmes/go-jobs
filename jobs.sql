CREATE TABLE IF NOT EXISTS job_statuses (
    id INTEGER PRIMARY KEY,
    public_id uuid NOT NULL UNIQUE DEFAULT uuidv7(),
    name TEXT NOT NULL UNIQUE,
    description TEXT
);

INSERT INTO job_statuses (id, public_id, name, description)
