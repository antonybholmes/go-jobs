-- function to automatically update the updated_at column
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
   NEW.updated_at = now();
   RETURN NEW;
END;
$$ LANGUAGE plpgsql;

 

CREATE TABLE IF NOT EXISTS jobs (
    id uuid PRIMARY KEY DEFAULT uuidv7(),
    user_id uuid NOT NULL,
    email TEXT NOT NULL,
    name TEXT,
    description TEXT,
    -- The type of job (e.g., "email", "crispr")
    type TEXT NOT NULL,
    -- The timestamp when the job was created
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TRIGGER update_jobs_updated_at
BEFORE UPDATE ON jobs
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

CREATE TABLE IF NOT EXISTS file_types (
    id uuid PRIMARY KEY DEFAULT uuidv7(),
    name TEXT NOT NULL,
    description TEXT
);

INSERT INTO file_types ( name, description)
VALUES
    ( 'input', 'Files user uploads'),
    ( 'output', 'Files generated by jobs');   

CREATE TABLE IF NOT EXISTS files (
    id uuid PRIMARY KEY DEFAULT uuidv7(),
    job_id uuid NOT NULL REFERENCES jobs(id),
    file_type_id uuid NOT NULL REFERENCES file_types(id),
    bucket TEXT NOT NULL,
    object_key TEXT NOT NULL,
    filename TEXT NOT NULL,
    content_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TRIGGER update_files_updated_at
BEFORE UPDATE ON files
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();


CREATE TABLE IF NOT EXISTS job_outbox (
    id uuid PRIMARY KEY,
    job_id uuid NOT NULL REFERENCES jobs(id),
    payload jsonb NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    published_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS job_outbox_pending_idx
    ON job_outbox (job_id, created_at) WHERE published_at IS NULL;
