CREATE TABLE IF NOT EXISTS job_types (
    id INTEGER PRIMARY KEY,
    public_id uuid NOT NULL UNIQUE DEFAULT uuidv7(),
    name TEXT NOT NULL UNIQUE,
    description TEXT
);

